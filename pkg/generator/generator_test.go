func TestWriteLauncher(t *testing.T) {
	tempDir := t.TempDir()

	res, err := SynthesizeLauncher("testtool", "testapp", "testbin")
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}

	writtenPath, err := WriteLauncher(tempDir, res)
	if err != nil {
		t.Fatalf("failed to write launcher: %v", err)
	}

	expectedPath := filepath.Join(tempDir, "usr", "bin", "testtool")
	if writtenPath != expectedPath {
		t.Errorf("expected written path '%s', got '%s'", expectedPath, writtenPath)
	}

	fi, err := os.Stat(writtenPath)
	if err != nil {
		t.Fatalf("failed to stat written launcher: %v", err)
	}

	if fi.Mode().Perm() != fsutil.ExecMode {
		t.Errorf("expected permissions 0755, got %v", fi.Mode().Perm())
	}

	data, err := os.ReadFile(writtenPath)
	if err != nil {
		t.Fatalf("failed to read written launcher: %v", err)
	}

	if !bytes.Equal(data, res.Content) {
		t.Errorf("written content does not match synthesized content")
	}
}

// TestLauncher_POSIXExecContractAndArgumentForwarding executes the synthesized launcher script
// to verify the core operational semantics mandated by Requirement 3:
// 1. Argument forwarding without word-splitting or shell interpretation
// 2. Direct STDIN/STDOUT/STDERR stream passthrough
// 3. Transparent exit code propagation
// 4. PID preservation via POSIX exec (replacing the wrapper process)
func TestLauncher_POSIXExecContractAndArgumentForwarding(t *testing.T) {
	tempDir := t.TempDir()

	// 1. Create mock payload script
	payloadDir := filepath.Join(tempDir, "payload")
	if err := os.MkdirAll(payloadDir, 0755); err != nil {
		t.Fatalf("failed to create payload dir: %v", err)
	}
	payloadPath := filepath.Join(payloadDir, "target")

	mockPayloadScript := `#!/bin/sh
case "$1" in
  --print-args)
    shift
    for arg in "$@"; do
      printf 'ARG:[%s]\n' "$arg"
    done
    ;;
  --echo-stdin)
    cat
    ;;
  --exit-code)
    exit "$2"
    ;;
  --pid-check)
    echo "$$"
    ;;
  *)
    echo "UNKNOWN"
    exit 1
    ;;
esac
`
	if err := os.WriteFile(payloadPath, []byte(mockPayloadScript), 0755); err != nil {
		t.Fatalf("failed to write mock payload: %v", err)
	}

	// 2. Synthesize a proxy launcher.
	// Since in this unit test we are running in tempDir rather than the root filesystem,
	// we create a launcher that uses the same exec logic targeting payloadPath.
	launcherScript := fmt.Sprintf(`#!/bin/sh
# Auto-generated by Craftpack. Do not edit.

REAL_PAYLOAD="%s"

exec "$REAL_PAYLOAD" "$@"
`, payloadPath)

	launcherPath := filepath.Join(tempDir, "launcher.sh")
	if err := os.WriteFile(launcherPath, []byte(launcherScript), 0755); err != nil {
		t.Fatalf("failed to write launcher script: %v", err)
	}

	// Test A: Argument forwarding with complex spaces, quotes, and symbols
	testArgs := []string{
		"--print-args",
		"simple",
		"two words with spaces",
		"single'quote",
		"double\"quote",
		"$VAR_LITERAL",
		"--flag=value with space",
		"*glob*",
		"-v",
		"",
	}

	cmd := exec.Command("/bin/sh", append([]string{launcherPath}, testArgs...)...)
	outBytes, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("launcher execution failed: %v, output:\n%s", err, string(outBytes))
	}

	outStr := string(outBytes)
	for _, expectedArg := range testArgs[1:] { // skip --print-args
		expectedLine := fmt.Sprintf("ARG:[%s]", expectedArg)
		if !strings.Contains(outStr, expectedLine) {
			t.Errorf("expected output to contain '%s', got:\n%s", expectedLine, outStr)
		}
	}

	// Test B: Exit code propagation (test codes 0, 42, 127)
	for _, code := range []int{0, 42, 127} {
		cmdExit := exec.Command(launcherPath, "--exit-code", fmt.Sprintf("%d", code))
		errExit := cmdExit.Run()
		if code == 0 {
			if errExit != nil {
				t.Errorf("expected exit code 0, got err: %v", errExit)
			}
		} else {
			if exitErr, ok := errExit.(*exec.ExitError); ok {
				if exitErr.ExitCode() != code {
					t.Errorf("expected exit code %d, got %d", code, exitErr.ExitCode())
				}
			} else {
				t.Errorf("expected ExitError for code %d, got %v", code, errExit)
			}
		}
	}

	// Test C: Stdin stream passthrough
	inputMessage := "Testing stdin passthrough across exec proxy barrier\nLine 2 payload"
	cmdStdin := exec.Command(launcherPath, "--echo-stdin")
	cmdStdin.Stdin = strings.NewReader(inputMessage)
	outStdin, err := cmdStdin.Output()
	if err != nil {
		t.Fatalf("stdin passthrough failed: %v", err)
	}
	if string(outStdin) != inputMessage {
		t.Errorf("expected stdin output '%s', got '%s'", inputMessage, string(outStdin))
	}

	// Test D: PID preservation (POSIX exec contract)
	// Execute in a subshell: echo shell PID, then exec launcher; the payload PID must equal shell PID
	subshellCmd := fmt.Sprintf(`echo -n "SHELL:$$ "; exec "%s" --pid-check`, launcherPath)
	cmdPID := exec.Command("/bin/sh", "-c", subshellCmd)
	outPIDBytes, err := cmdPID.CombinedOutput()
	if err != nil {
		t.Fatalf("PID check failed: %v, output: %s", err, string(outPIDBytes))
	}
	fields := strings.Fields(string(outPIDBytes))
	if len(fields) != 2 {
		t.Fatalf("unexpected PID output: %s", string(outPIDBytes))
	}
	shellPID := strings.TrimPrefix(fields[0], "SHELL:")
	payloadPID := fields[1]
	if shellPID != payloadPID {
		t.Errorf("expected PID preservation under exec: shell PID %s != payload PID %s", shellPID, payloadPID)
	}
}

