func TestGenerateLauncher_Valid(t *testing.T) {
	tests := []struct {
		name       string
		appID      string
		entrypoint string
		wantAnchor string
	}{
		{
			name:       "standard app and binary",
			appID:      "craftpack",
			entrypoint: "craftpack",
			wantAnchor: `REAL_PAYLOAD="/usr/lib/craftpack/craftpack"`,
		},
		{
			name:       "nested entrypoint path",
			appID:      "my-service",
			entrypoint: "bin/server",
			wantAnchor: `REAL_PAYLOAD="/usr/lib/my-service/bin/server"`,
		},
		{
			name:       "underscored app id",
			appID:      "app_daemon",
			entrypoint: "app_daemon",
			wantAnchor: `REAL_PAYLOAD="/usr/lib/app_daemon/app_daemon"`,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			content, err := GenerateLauncher(tt.appID, tt.entrypoint)
			if err != nil {
				t.Fatalf("unexpected error: %v", err)
			}

			script := string(content)

			// Section 5.1 & Requirement 3 contracts:
			if !strings.HasPrefix(script, "#!/bin/sh\n") {
				t.Errorf("expected script to start with '#!/bin/sh\\n', got:\n%s", script)
			}
			if !strings.Contains(script, "# Auto-generated by Craftpack. Do not edit.") {
				t.Errorf("missing craftpack autogen comment")
			}
			if !strings.Contains(script, tt.wantAnchor) {
				t.Errorf("expected anchor '%s', got script:\n%s", tt.wantAnchor, script)
			}
			if !strings.Contains(script, `exec "$REAL_PAYLOAD" "$@"`) {
				t.Errorf("missing POSIX exec delegation line in script:\n%s", script)
			}
			if !strings.HasSuffix(script, "\n") {
				t.Errorf("expected script to end with newline")
			}
		})
	}
}

