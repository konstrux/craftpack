// TestManPage_SystemManToolIntegration tests that the synthesized roff document can be parsed
// and formatted by the host system's `man` binary without syntax errors.
func TestManPage_SystemManToolIntegration(t *testing.T) {
	manPath, err := exec.LookPath("man")
	if err != nil {
		t.Skip("system 'man' binary not found on host, skipping integration test")
	}

	rawMarkdown := `# NAME
sample \- a sample utility for man page testing

# SYNOPSIS
**sample** [**\--verbose**] [*argument*...]

# DESCRIPTION
This is a test description verifying host man utility compatibility.
`
	meta := ManPageMetadata{
		Title:   "SAMPLE",
		Section: 1,
		Date:    "2026-09-06",
		Header:  "User Commands Manual",
		Footer:  "sample 1.0.0",
	}

	roffBytes, err := RenderRoff([]byte(rawMarkdown), meta)
	if err != nil {
		t.Fatalf("failed to render roff: %v", err)
	}

	// Invoke `man -l -` feeding roff into stdin
	cmd := exec.Command(manPath, "-l", "-")
	cmd.Stdin = bytes.NewReader(roffBytes)
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("system 'man' failed to parse generated roff: %v\nOutput:\n%s\nRoff:\n%s", err, string(out), string(roffBytes))
	}

	formatted := string(out)
	if !strings.Contains(formatted, "SAMPLE") {
		t.Errorf("expected formatted man page to contain 'SAMPLE', got:\n%s", formatted)
	}
	if !strings.Contains(formatted, "SYNOPSIS") {
		t.Errorf("expected formatted man page to contain 'SYNOPSIS', got:\n%s", formatted)
	}
}
