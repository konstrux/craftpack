package generator

import (
	"bytes"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"text/template"

	"craftpack/pkg/fsutil"
	"craftpack/pkg/spec"
)

var (
	// ErrInvalidAppID is returned when an application identifier fails validation.
	ErrInvalidAppID = errors.New("invalid application ID: must be non-empty lowercase alphanumeric identifier")

	// ErrInvalidEntrypoint is returned when an entrypoint path is invalid or attempts traversal.
	ErrInvalidEntrypoint = errors.New("invalid entrypoint path: must be a clean relative path")

	// ErrInvalidCommand is returned when a command name contains path separators or invalid characters.
	ErrInvalidCommand = errors.New("invalid command name: must be a simple filename without path separators")
)

var (
	// appIDRegex validates sanitized app IDs (lowercase alphanumeric, single hyphens or underscores).
	appIDRegex = regexp.MustCompile(`^[a-z0-9]([a-z0-9-_]*[a-z0-9])?$`)

	// commandRegex validates command names (alphanumeric, hyphens, underscores).
	commandRegex = regexp.MustCompile(`^[a-z0-9-_]+$`)
)

// LauncherScriptTemplate defines the POSIX-compliant proxy launcher shell script template.
// Conforms strictly to Section 5.1 of the Craftpack specification.
const LauncherScriptTemplate = `#!/bin/sh
# Auto-generated by Craftpack. Do not edit.

# Absolute path anchoring to prevent path-hijacking vulnerabilities
REAL_PAYLOAD="/usr/lib/{{.AppID}}/{{.Entrypoint}}"

# Securely delegate execution using POSIX exec to preserve PID and signal propagation
exec "$REAL_PAYLOAD" "$@"
`

// LauncherData holds the template parameters for launcher script synthesis.
type LauncherData struct {
	AppID      string
	Entrypoint string
}

// LauncherResult encapsulates the output of the launcher synthesis engine.
type LauncherResult struct {
	Command         string      // Command name (e.g., "craftpack")
	AppID           string      // Sanitized application ID (e.g., "craftpack")
	Entrypoint      string      // Relative entrypoint path within /usr/lib/<app_id>/
	DestinationPath string      // Absolute system target path (e.g., "/usr/bin/craftpack")
	Content         []byte      // Executable shell script content
	Mode            os.FileMode // Normalized file permissions (0755)
}

// RelPath returns the relative destination path suitable for tar archive serialization.
func (r *LauncherResult) RelPath() string {
	return strings.TrimPrefix(r.DestinationPath, "/")
}

// SanitizeAppID validates and sanitizes an application identifier.
func SanitizeAppID(appID string) (string, error) {
	trimmed := strings.ToLower(strings.TrimSpace(appID))
	if trimmed == "" {
		return "", ErrInvalidAppID
	}
	if !appIDRegex.MatchString(trimmed) {
		return "", fmt.Errorf("%w: '%s'", ErrInvalidAppID, appID)
	}
	return trimmed, nil
}

// SanitizeEntrypoint validates and sanitizes an application entrypoint path.
func SanitizeEntrypoint(entrypoint string) (string, error) {
	trimmed := strings.TrimSpace(entrypoint)
	if trimmed == "" {
		return "", ErrInvalidEntrypoint
	}
	if filepath.IsAbs(trimmed) {
		return "", fmt.Errorf("%w: entrypoint cannot be an absolute path ('%s')", ErrInvalidEntrypoint, entrypoint)
	}
	clean := filepath.Clean(trimmed)
	if clean == "." || clean == ".." || strings.HasPrefix(clean, ".."+string(filepath.Separator)) || strings.HasPrefix(clean, "../") {
		return "", fmt.Errorf("%w: entrypoint cannot traverse outside payload directory ('%s')", ErrInvalidEntrypoint, entrypoint)
	}
	if strings.ContainsAny(clean, "\"\n\r\t\x00`$") {
		return "", fmt.Errorf("%w: entrypoint contains illegal characters", ErrInvalidEntrypoint)
	}
	return filepath.ToSlash(clean), nil
}

// SanitizeCommand validates and sanitizes a user-facing command name.
func SanitizeCommand(command string) (string, error) {
	trimmed := strings.TrimSpace(command)
	if trimmed == "" {
		return "", ErrInvalidCommand
	}
	if strings.ContainsAny(trimmed, "/\\") {
		return "", fmt.Errorf("%w: command cannot contain directory separators ('%s')", ErrInvalidCommand, command)
	}
	if !commandRegex.MatchString(trimmed) {
		return "", fmt.Errorf("%w: command contains invalid characters ('%s')", ErrInvalidCommand, command)
	}
	return trimmed, nil
}

// GenerateLauncher synthesizes the POSIX shell proxy launcher script bytes given an AppID and Entrypoint.
func GenerateLauncher(appID, entrypoint string) ([]byte, error) {
	sanitizedAppID, err := SanitizeAppID(appID)
	if err != nil {
		return nil, err
	}

	sanitizedEntrypoint, err := SanitizeEntrypoint(entrypoint)
	if err != nil {
		return nil, err
	}

	data := LauncherData{
		AppID:      sanitizedAppID,
		Entrypoint: sanitizedEntrypoint,
	}

	tmpl, err := template.New("launcher").Parse(LauncherScriptTemplate)
	if err != nil {
		return nil, fmt.Errorf("failed to parse launcher template: %w", err)
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return nil, fmt.Errorf("failed to execute launcher template: %w", err)
	}

	return buf.Bytes(), nil
}

// SynthesizeLauncher builds the complete LauncherResult including destination path and permissions.
func SynthesizeLauncher(command, appID, entrypoint string) (*LauncherResult, error) {
	sanitizedCommand, err := SanitizeCommand(command)
	if err != nil {
		return nil, err
	}

	content, err := GenerateLauncher(appID, entrypoint)
	if err != nil {
		return nil, err
	}

	sanitizedAppID, _ := SanitizeAppID(appID)
	sanitizedEntrypoint, _ := SanitizeEntrypoint(entrypoint)

	return &LauncherResult{
		Command:         sanitizedCommand,
		AppID:           sanitizedAppID,
		Entrypoint:      sanitizedEntrypoint,
		DestinationPath: "/usr/bin/" + sanitizedCommand,
		Content:         content,
		Mode:            fsutil.ExecMode,
	}, nil
}

// SynthesizeLauncherFromConfig synthesizes a launcher using parameters from CraftpackConfig.
func SynthesizeLauncherFromConfig(cfg *spec.CraftpackConfig) (*LauncherResult, error) {
	if cfg == nil {
		return nil, errors.New("craftpack config cannot be nil")
	}
	command := cfg.Command
	if command == "" {
		command = cfg.Name
	}
	return SynthesizeLauncher(command, cfg.Name, cfg.Entrypoint)
}

// WriteLauncher writes the synthesized launcher to destDir (e.g. staging root) with 0755 permissions.
func WriteLauncher(destDir string, res *LauncherResult) (string, error) {
	if res == nil {
		return "", errors.New("launcher result cannot be nil")
	}
	cleanRel := strings.TrimPrefix(filepath.Clean(res.DestinationPath), "/")
	fullDest := filepath.Join(destDir, cleanRel)

	if err := os.MkdirAll(filepath.Dir(fullDest), fsutil.DirMode); err != nil {
		return "", fmt.Errorf("failed to create launcher directory: %w", err)
	}

	if err := os.WriteFile(fullDest, res.Content, res.Mode); err != nil {
		return "", fmt.Errorf("failed to write launcher file: %w", err)
	}

	return fullDest, nil
}
